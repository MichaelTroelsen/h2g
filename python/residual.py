"""Which songs sound worse than their register columns say, and by how much.

    python residual.py --from-json ../build/fidelity.json -o ../build/residual.md

Read-only over a `fidelity.py --json` run taken with `--sound`. For each song
the residual is `reg_mean - aud`, where `reg_mean` is the mean of the
per-frame register agreements `wave`, `adsr` and `gate` present on the row.
A large residual means the rendered sound disagrees with the original by more
than the registers the report reads can account for -- a blind spot, or a
defect in a register no column compares.

WHY THOSE THREE AND NOT `melody`: melody reads ~100% on almost every row, so
averaging it in shrinks every residual's spread by a quarter without adding
information. It stays visible in the table, outside the mean.

A RESIDUAL IS A LEAD, NOT A MEASUREMENT. Two things make a row's number mean
less than it looks, and each is flagged in `explained_by` rather than
filtered out:

  * `short-window` -- the row was scored over fewer than `SHORT_WINDOW_S`
    seconds (Kings_of_the_Beach_ingame is 8 s), so a few frames decide it.
  * `coverage` -- the window held under `LOW_COVERAGE` of the original's own
    length. Not raised where `window_coverage_bounded` is set: that row's
    original never ends, and its figure is fidelity.py's "<10%" ceiling.

Later columns (`vol`, `res`, `ctrl`, ...) add their own names to
`explained_by` when they account for a row's deficit.

Held files (`hold.ON_HOLD`) are measured with everything else and listed in
their own table: no task may target one, so they are never ranked.
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

import hold

REG_COLUMNS = ("wave", "adsr", "gate")
SHORT_WINDOW_S = 60
LOW_COVERAGE = 0.2


def _entry(row: dict) -> dict:
    regs = [row[k] for k in REG_COLUMNS if row.get(k) is not None]
    reg_mean = sum(regs) / len(regs) if regs else None
    aud = row["aud"]
    explained = []
    if (row.get("window_seconds") or 0) < SHORT_WINDOW_S:
        explained.append("short-window")
    if (row.get("window_coverage") is not None and row["window_coverage"] < LOW_COVERAGE
            and not row.get("window_coverage_bounded")):
        explained.append("coverage")
    reason = hold.held(row["file"])
    return {
        "file": row["file"],
        "aud": aud,
        "loud": row.get("loud"),
        "loud_ratio": row.get("loud_ratio"),
        "melody": row.get("melody"),
        "reg_mean": reg_mean,
        "residual": None if reg_mean is None else reg_mean - aud,
        "multiplier": row.get("multiplier"),
        "window_seconds": row.get("window_seconds"),
        "held": reason is not None,
        "hold_reason": reason,
        "explained_by": explained,
    }


def residuals(rows: list[dict]) -> dict:
    """`ranked` (non-held, largest residual first), `held`, `unmeasured`.

    Raises ValueError when no row carries `aud`: a run taken without
    `--sound` would otherwise rank nothing and read like a clean corpus.
    """
    measured = [r for r in rows if r.get("aud") is not None]
    if not measured:
        raise ValueError("no row carries `aud` -- was the run taken with --sound?")
    entries = [_entry(r) for r in measured]
    ranked = sorted((e for e in entries if not e["held"] and e["residual"] is not None),
                    key=lambda e: e["residual"], reverse=True)
    return {
        "ranked": ranked,
        "held": [e for e in entries if e["held"]],
        "unmeasured": [r["file"] for r in rows if r.get("aud") is None],
    }


def _f(v, fmt="{:.3f}"):
    # round, then `+ 0.0`, so a float residue like -2.8e-17 prints +0.000, not -0.000
    return "-" if v is None else fmt.format(round(v, 3) + 0.0)


def _table(entries: list[dict]) -> list[str]:
    out = ["| file | residual | aud | reg_mean | melody | loud | loud_ratio | -S | window | explained_by |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for e in entries:
        out.append(f"| {e['file']} | {_f(e['residual'], '{:+.3f}')} | {_f(e['aud'])} | "
                   f"{_f(e['reg_mean'])} | {_f(e['melody'])} | {_f(e['loud'])} | "
                   f"{_f(e['loud_ratio'], '{:.2f}')} | {e['multiplier'] or '-'} | "
                   f"{_f(e['window_seconds'], '{:.0f} s')} | {', '.join(e['explained_by']) or '-'} |")
    return out


def report(result: dict, source: str) -> str:
    ranked = result["ranked"]
    med = statistics.median(e["residual"] for e in ranked) if ranked else None
    lines = [
        "# Residual triage",
        "",
        f"Generated by `python/residual.py` from `{source}`. residual = mean({', '.join(REG_COLUMNS)}) - aud. "
        f"{len(ranked)} ranked, {len(result['held'])} held, {len(result['unmeasured'])} unmeasured.",
        "",
        f"**Corpus median residual: {_f(med, '{:+.3f}')}.** Read the top of the table against this, "
        "not against zero: a row near the median is the corpus norm, not a lead.",
        "",
        "## Ranked (non-held)",
        "",
        *_table(ranked),
        "",
        "## On hold: DIGI (measured, never ranked or worked)",
        "",
        *_table(result["held"]),
        "",
        "## Unmeasured",
        "",
        ", ".join(result["unmeasured"]) or "(none)",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--from-json", required=True, help="a fidelity.py --json run taken with --sound")
    p.add_argument("-o", "--output", help="write the Markdown report here (default: stdout)")
    args = p.parse_args(argv)
    data = json.loads(Path(args.from_json).read_text(encoding="utf-8"))
    rows = data if isinstance(data, list) else data.get("rows", [])
    try:
        result = residuals(rows)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    md = report(result, args.from_json)
    if args.output:
        Path(args.output).write_text(md, encoding="utf-8")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
